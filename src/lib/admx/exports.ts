// Turns RFF baseline settings (the materializer's output) into things an admin can run: a .reg file, a PowerShell
// script that applies them, and a PowerShell script that CHECKS them and reports drift value by value, the same
// question RFF Conformance answers across a fleet. Pure; no DOM.

import type { PolicySetting } from './admxMaterialize';

const hive = (scope: string) => (scope === 'user' ? 'HKEY_CURRENT_USER' : 'HKEY_LOCAL_MACHINE');
const psHive = (scope: string) => (scope === 'user' ? 'HKCU:' : 'HKLM:');

/** Little-endian hex bytes for .reg hex(...) values, comma-separated. */
const hexBytes = (bytes: number[]) => bytes.map((b) => b.toString(16).padStart(2, '0')).join(',');
const utf16le = (s: string) => { const out: number[] = []; for (const ch of s) { const c = ch.codePointAt(0)!; if (c > 0xffff) { const v = c - 0x10000; const hi = 0xd800 + (v >> 10), lo = 0xdc00 + (v & 0x3ff); out.push(hi & 0xff, hi >> 8, lo & 0xff, lo >> 8); } else out.push(c & 0xff, c >> 8); } return out; };
const regString = (s: string) => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';

function regData(s: PolicySetting): string {
  const v = s.value ?? '';
  switch (s.kind) {
    case 'dword': return 'dword:' + (Number(BigInt.asUintN(32, BigInt(v || '0')))).toString(16).padStart(8, '0');
    case 'qword': { const n = BigInt.asUintN(64, BigInt(v || '0')); const b: number[] = []; for (let i = 0n; i < 8n; i++) b.push(Number((n >> (8n * i)) & 0xffn)); return 'hex(b):' + hexBytes(b); }
    case 'expand': return 'hex(2):' + hexBytes([...utf16le(v), 0, 0]);
    case 'multi': return 'hex(7):' + hexBytes([...v.split('\n').flatMap((l) => [...utf16le(l), 0, 0]), 0, 0]);
    default: return regString(v);
  }
}

/** A .reg file. Absent settings become "name"=- (delete the value). */
export function toReg(settings: PolicySetting[]): string {
  const lines = ['Windows Registry Editor Version 5.00', ''];
  const byKey = new Map<string, PolicySetting[]>();
  for (const s of settings) { const k = `${hive(s.scope)}\\${s.path}`; byKey.set(k, [...(byKey.get(k) ?? []), s]); }
  for (const [k, list] of byKey) {
    lines.push(`[${k}]`);
    for (const s of list) lines.push(`${regString(s.name)}=${s.absent ? '-' : regData(s)}`);
    lines.push('');
  }
  return lines.join('\r\n');
}

const psq = (s: string) => "'" + s.replace(/'/g, "''") + "'";
const PS_TYPE: Record<string, string> = { dword: 'DWord', qword: 'QWord', string: 'String', expand: 'ExpandString', multi: 'MultiString' };
const psValue = (s: PolicySetting) => {
  const v = s.value ?? '';
  if (s.kind === 'multi') return '@(' + v.split('\n').map(psq).join(', ') + ')';
  if (s.kind === 'dword' || s.kind === 'qword') return v || '0';
  return psq(v);
};

/** PowerShell that writes the settings (Windows PowerShell 5.1, pure ASCII). Run elevated for HKLM. */
export function toPowerShellApply(settings: PolicySetting[], title: string): string {
  const out = [`# ${ascii(title)}`, '# Writes these Group Policy registry values directly. Run elevated for HKLM.', '# Generated by getrff.com/admx/ from Microsoft\'s ADMX definitions.', ''];
  for (const s of settings) {
    const path = `${psHive(s.scope)}\\${s.path}`;
    if (s.absent) out.push(`Remove-ItemProperty -Path ${psq(path)} -Name ${psq(s.name)} -ErrorAction SilentlyContinue`);
    else {
      out.push(`if (-not (Test-Path ${psq(path)})) { New-Item -Path ${psq(path)} -Force | Out-Null }`);
      out.push(`Set-ItemProperty -Path ${psq(path)} -Name ${psq(s.name)} -Type ${PS_TYPE[s.kind] ?? 'String'} -Value ${psValue(s)}`);
    }
  }
  return out.join('\r\n') + '\r\n';
}

/** PowerShell that reads each value and reports OK or DRIFT, like one Conformance check on one machine. Changes nothing. */
export function toPowerShellCheck(settings: PolicySetting[], title: string): string {
  const rows = settings.map((s) => `  @{ Path = ${psq(`${psHive(s.scope)}\\${s.path}`)}; Name = ${psq(s.name)}; Absent = $${s.absent ? 'true' : 'false'}; Want = ${s.absent ? '$null' : psValue(s)} }`);
  return [
    `# Checks: ${ascii(title)}`,
    '# Reads each value and prints OK or DRIFT. Changes nothing. Generated by getrff.com/admx/.',
    '$want = @(',
    rows.join(",\r\n"),
    ')',
    '$drift = 0',
    'foreach ($w in $want) {',
    '  $item = Get-ItemProperty -Path $w.Path -Name $w.Name -ErrorAction SilentlyContinue',
    '  $have = if ($item) { $item.($w.Name) } else { $null }',
    '  if ($w.Absent) { $ok = ($null -eq $item) } else { $ok = ($null -ne $item) -and ((@($have) -join "`n") -eq (@($w.Want) -join "`n")) }',
    '  if (-not $ok) { $drift++ }',
    '  $shown = if ($null -eq $item) { "(not set)" } else { (@($have) -join ", ") }',
    '  "{0,-6} {1}\\{2} = {3}" -f $(if ($ok) { "OK" } else { "DRIFT" }), $w.Path, $w.Name, $shown',
    '}',
    'if ($drift) { "$drift value(s) differ." ; exit 1 } else { "All values match." }',
  ].join('\r\n') + '\r\n';
}

/** Windows PowerShell 5.1 fails to parse non-ASCII silently; keep generated comments ASCII. */
const ascii = (s: string) => s.replace(/[^\x20-\x7e]/g, '?');
